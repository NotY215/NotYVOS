extern "C" bool notyvos_aes_unwrap(const notyvos::u8* kek, const notyvos::u8* in,
                                   notyvos::usize in_len, notyvos::u8* out) noexcept
{
    if ((in_len & 7u) != 0 || in_len < 16)
        return false;
    const usize n = in_len / 8u - 1u;

    u8 a[8];
    u8 r[512];
    for (u32 i = 0; i < 8; ++i)
        a[i] = in[i];
    for (usize i = 0; i < n * 8u; ++i)
        r[i] = in[8u + i];

    u8 rk[176];
    aes_expand_key(kek, rk);

    for (int j = 5; j >= 0; --j)
    {
        for (int i = static_cast<int>(n); i >= 1; --i)
        {
            u8 t[16];
            u64 tval = 0;
            for (u32 k = 0; k < 8; ++k)
                tval = (tval << 8) | a[k];
            tval ^= static_cast<u64>(n) * static_cast<u64>(j) + static_cast<u64>(i);
            for (u32 k = 0; k < 8; ++k)
                t[k] = static_cast<u8>((tval >> ((7u - k) * 8u)) & 0xFFu);
            const usize row = static_cast<usize>(i - 1) * 8u;
            for (u32 k = 0; k < 8; ++k)
                t[8u + k] = r[row + k];

            u8 plain[16];
            aes_decrypt_block(rk, t, plain);

            for (u32 k = 0; k < 8; ++k)
                a[k] = plain[k];
            for (u32 k = 0; k < 8; ++k)
                r[row + k] = plain[8u + k];
        }
    }

    const u8 iv[] = {0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6};
    for (u32 i = 0; i < 8; ++i)
        if (a[i] != iv[i])
            return false;

    for (usize i = 0; i < n * 8u; ++i)
        out[i] = r[i];
    return true;
}
