const u8 rcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

inline u8 xtime(u8 x) noexcept
{
    return static_cast<u8>((x << 1) ^ ((x >> 7) * 0x1b));
}

inline u8 gf_mul(u8 a, u8 b) noexcept
{
    u8 r = 0;
    while (b)
    {
        if (b & 1u)
            r = static_cast<u8>(r ^ a);
        a = xtime(a);
        b = static_cast<u8>(b >> 1);
    }
    return r;
}

void aes_expand_key(const u8* key, u8* rk) noexcept
{
    for (u32 i = 0; i < 16; ++i)
        rk[i] = key[i];
    for (u32 i = 4; i < 44; ++i)
    {
        u8 t[4];
        for (u32 k = 0; k < 4; ++k)
            t[k] = rk[(i - 1) * 4 + k];
        if (i % 4 == 0)
        {
            const u8 tmp = t[0];
            t[0] = static_cast<u8>(sbox[t[1]] ^ rcon[i / 4]);
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[tmp];
        }
        for (u32 k = 0; k < 4; ++k)
            rk[i * 4 + k] = static_cast<u8>(rk[(i - 4) * 4 + k] ^ t[k]);
    }
}

void aes_decrypt_block(const u8* rk, const u8* in, u8* out) noexcept
{
    u8 s[16];
    for (u32 i = 0; i < 16; ++i)
        s[i] = static_cast<u8>(in[i] ^ rk[160 + i]);

    for (int rnd = 9; rnd >= 0; --rnd)
    {
        u8 t[16];
        t[0] = s[0];
        t[1] = s[13];
        t[2] = s[10];
        t[3] = s[7];
        t[4] = s[4];
        t[5] = s[1];
        t[6] = s[14];
        t[7] = s[11];
        t[8] = s[8];
        t[9] = s[5];
        t[10] = s[2];
        t[11] = s[15];
        t[12] = s[12];
        t[13] = s[9];
        t[14] = s[6];
        t[15] = s[3];
        for (u32 i = 0; i < 16; ++i)
            s[i] = t[i];

        for (u32 i = 0; i < 16; ++i)
            s[i] = rsbox[s[i]];

        const u32 rk_base = static_cast<u32>(rnd) * 16u;
        for (u32 i = 0; i < 16; ++i)
            s[i] = static_cast<u8>(s[i] ^ rk[rk_base + i]);

        for (u32 c = 0; c < 4; ++c)
        {
            u8* col = s + c * 4;
            const u8 a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
            col[0] = static_cast<u8>(gf_mul(a0, 0x0e) ^ gf_mul(a1, 0x0b) ^ gf_mul(a2, 0x0d) ^
                                     gf_mul(a3, 0x09));
            col[1] = static_cast<u8>(gf_mul(a0, 0x09) ^ gf_mul(a1, 0x0e) ^ gf_mul(a2, 0x0b) ^
                                     gf_mul(a3, 0x0d));
            col[2] = static_cast<u8>(gf_mul(a0, 0x0d) ^ gf_mul(a1, 0x09) ^ gf_mul(a2, 0x0e) ^
                                     gf_mul(a3, 0x0b));
            col[3] = static_cast<u8>(gf_mul(a0, 0x0b) ^ gf_mul(a1, 0x0d) ^ gf_mul(a2, 0x09) ^
                                     gf_mul(a3, 0x0e));
        }
    }

    u8 t[16];
    t[0] = s[0];
    t[1] = s[13];
    t[2] = s[10];
    t[3] = s[7];
    t[4] = s[4];
    t[5] = s[1];
    t[6] = s[14];
    t[7] = s[11];
    t[8] = s[8];
    t[9] = s[5];
    t[10] = s[2];
    t[11] = s[15];
    t[12] = s[12];
    t[13] = s[9];
    t[14] = s[6];
    t[15] = s[3];
    for (u32 i = 0; i < 16; ++i)
        s[i] = rsbox[t[i]];
    for (u32 i = 0; i < 16; ++i)
        out[i] = static_cast<u8>(s[i] ^ rk[i]);
}

